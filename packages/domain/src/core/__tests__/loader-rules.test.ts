import { describe, expect, it } from 'vitest';
import { LOADER_RULE_MARKER, LOADER_RULE_PREFIX, diffLoaderRules, renderLoaderRules } from '../loader-rules.js';
import { parseRegistry } from '../registry.js';

const REGISTRY = `version: 1
contexts:
  - id: lending
    name: Lending
    card: docs/domain/lending/domain.md
    paths: ["src/Lending/**", "src/Holds/**"]
    rung: named
  - id: billing
    name: Billing
    paths: ["src/Billing/**"]
    rung: fear
`;

function registry() {
  const parsed = parseRegistry(REGISTRY);
  if (!parsed.registry) throw new Error(JSON.stringify(parsed.problems));
  return parsed.registry;
}

const CLAUDE = `---
paths:
  - "src/Lending/**"
  - "src/Holds/**"
---
<!-- generated by ctxo domain rules; do not edit -->
# Lending context
Before changing code under these paths, read \`docs/domain/lending/domain.md\` (rules, contracts, decisions).
If behaviour changes, update that card in the same PR. If it does not, add \`Domain-Unchanged: lending (reason)\` to a commit.
`;

const CURSOR = `---
description: Lending context: read docs/domain/lending/domain.md before changing this code
globs: src/Lending/**,src/Holds/**
alwaysApply: false
---
<!-- generated by ctxo domain rules; do not edit -->
# Lending context
Before changing code under these paths, read \`docs/domain/lending/domain.md\` (rules, contracts, decisions).
If behaviour changes, update that card in the same PR. If it does not, add \`Domain-Unchanged: lending (reason)\` to a commit.
`;

describe('renderLoaderRules', () => {
  it('renders the spec example for Claude Code and Cursor', () => {
    const files = renderLoaderRules(registry(), ['claude-code', 'cursor']);
    expect(files).toEqual([
      { path: '.claude/rules/ctxo-context-lending.md', content: CLAUDE },
      { path: '.cursor/rules/ctxo-context-lending.mdc', content: CURSOR },
    ]);
  });

  it('contexts without a card get no file', () => {
    const paths = renderLoaderRules(registry(), ['claude-code', 'cursor']).map((f) => f.path);
    expect(paths.some((p) => p.includes('billing'))).toBe(false);
  });

  it('uses the ctxo-context- prefix', () => {
    expect(LOADER_RULE_PREFIX).toBe('ctxo-context-');
    for (const f of renderLoaderRules(registry(), ['claude-code', 'cursor'])) {
      expect(f.path).toContain(`/${LOADER_RULE_PREFIX}`);
    }
  });
});

describe('diffLoaderRules', () => {
  const expected = renderLoaderRules(registry(), ['claude-code', 'cursor']);

  it('reports missing, outdated, stale and foreign files and ignores CRLF and a BOM', () => {
    const existing = new Map<string, string>([
      ['.claude/rules/ctxo-context-lending.md', `﻿${CLAUDE.replace(/\n/g, '\r\n')}`],
      ['.cursor/rules/ctxo-context-lending.mdc', `${CURSOR}extra\n`],
      ['.claude/rules/ctxo-context-gone.md', `---\npaths:\n  - "x/**"\n---\n${LOADER_RULE_MARKER}\n# Gone\n`],
      ['.claude/rules/ctxo-context-mine.md', '# my own rule\n'],
    ]);
    expect(diffLoaderRules(expected, existing)).toEqual({
      missing: [],
      outdated: ['.cursor/rules/ctxo-context-lending.mdc'],
      stale: ['.claude/rules/ctxo-context-gone.md'],
      foreign: ['.claude/rules/ctxo-context-mine.md'],
      blocked: [],
    });
    const quoted = new Map([['.claude/rules/ctxo-context-lending.md', `# mine\n${LOADER_RULE_MARKER}\n`]]);
    expect(diffLoaderRules(expected, quoted).blocked).toEqual(['.claude/rules/ctxo-context-lending.md']);
    expect(diffLoaderRules(expected, new Map()).missing).toEqual(expected.map((f) => f.path));
  });
});
